"""Fill README.md's generated verification block, and check every number in README.md against the ledger.

Generated block (between GEN_START and GEN_END): claim counts by status (data/ledger.sqlite), saved briefs
that pass validate_brief.py now, review flags by severity (outputs/briefs/*.review.json), and the last full
local verification (outputs/verification_snapshot.json). Nothing in it is typed by hand.

Number check, for every README line outside the generated block, fenced code, and the tooling and
bibliography sections (SKIP_SECTIONS); inline code and link targets are ignored:
- A line with a marker <!-- claims: id id … --> may use only numbers found in those claims, at the printed
  precision (same rule as validate_brief.py). Its location references (Kuva N, Taulukko N, §x.y, measure
  x.y.z, p./pp. page numbers) must appear in the cited claims' location or notes. The claims must exist and
  be citable.
- A line without a marker may use only FRAME numbers and the numbers inside EXEMPT phrases.
- Terminology, on every line: the 22 rows of the report's county table are "regions" (21 wellbeing
  services counties and the City of Helsinki); "county" is kept for named counties (generic_county).

Usage: uv run python src/build_readme.py           # rewrite the block, then check
       uv run python src/build_readme.py --check   # write nothing; fail if the block is stale or a check fails
"""
import glob
import hashlib
import json
import re
import sys
from collections import Counter
from datetime import datetime
from pathlib import Path

import counties
import ledger
from validate_brief import FRAME_NUMBERS, claim_numbers, load_claims, matches, numbers, validate

README = Path("README.md")
SNAPSHOT = Path("outputs/verification_snapshot.json")
BRIEFS = Path("outputs/briefs")
GEN_START = "<!-- generated by src/build_readme.py: do not edit by hand -->"
GEN_END = "<!-- end generated -->"
MARKER = re.compile(r"<!--\s*claims:\s*([^>]*?)\s*-->")

# Sections that hold commands, versions, file names and document titles, not findings.
SKIP_SECTIONS = {"Run it", "Deploy on Streamlit Community Cloud", "Data sources"}
# Regions in the report's county table (Taulukko 11, counties.FULL): the wellbeing services counties
# ("… hyvinvointialue") plus the City of Helsinki ("Helsingin kaupunki").
N_REGIONS = len(counties.FULL)
N_WELLBEING_COUNTIES = sum(v.endswith("hyvinvointialue") for v in counties.FULL.values())
assert N_REGIONS == N_WELLBEING_COUNTIES + 1 and "Helsingin kaupunki" in counties.FULL.values()
# Numbers that describe the study frame: report years, CI level, follow-up months, and the region counts
# ("all 22 regions: the 21 wellbeing services counties and the City of Helsinki").
FRAME = set(FRAME_NUMBERS) | {float(N_REGIONS), float(N_WELLBEING_COUNTIES)}
# Terminology: "county" only for named counties ("Kymenlaakso county") and in the definition "wellbeing
# services counties"; all 22 together are "regions".
COUNTY_WORD = re.compile(r"\bcount(?:y|ies)\b", re.I)
COUNTY_OK_BEFORE = re.compile(
    r"(?:wellbeing services|" + "|".join(re.escape(k) for k in counties.FULL) + r")\s+$", re.I)


def generic_county(line: str) -> list[str]:
    """Generic uses of 'county'/'counties' in a line (not after a county name or 'wellbeing services')."""
    return [m.group(0) for m in COUNTY_WORD.finditer(line) if not COUNTY_OK_BEFORE.search(line[:m.start()])]
# Numbers that are not findings, each with the reason it is allowed.
EXEMPT = {
    "Junction 2026": "event name",
    "2-minute video": "video length",
    "20+ years": "team bio, supplied by the team",
}

LOC_TEXT = re.compile(r"Kuva \d+|Taulukko \d+|§\s?\d+(?:\.\d+)*|\b\d+\.\d+\.\d+\b")
_PAGE = r"\d+(?:\s?[–-]\s?\d+)?"
PAGES = re.compile(rf"\bpp?\.\s?{_PAGE}(?:,\s?{_PAGE})*")     # p.5, pp.52–53, pp.16, 24


def pages(text: str) -> set[int]:
    out = set()
    for ref in PAGES.findall(text or ""):
        for a, b in re.findall(r"(\d+)(?:\s?[–-]\s?(\d+))?", ref[ref.index(".") + 1:]):
            out.update(range(int(a), int(b or a) + 1))
    return out


def norm(s: str) -> str:
    return re.sub(r"\s+", "", s or "")


def generated_block(claims: dict[str, dict]) -> str:
    status = Counter(c["status"] for c in claims.values())
    quotes = sum(1 for c in claims.values() if c.get("quote"))
    citable = sum(n for s, n in status.items() if s in ledger.CITABLE)

    valid, total = 0, 0
    for short in counties.FULL:
        path = BRIEFS / f"{counties.slug(short)}.json"
        total += 1
        if path.exists():
            doc = json.loads(path.read_text(encoding="utf-8"))
            ids = set(doc.get("provided_claim_ids") or []) or None
            valid += not validate(doc["brief"], ids, claims) and doc["status"] != "DRAFT"

    sev = Counter()
    for f in glob.glob(str(BRIEFS / "*.review.json")):
        for flag in json.loads(Path(f).read_text(encoding="utf-8"))["flags"]:
            sev[flag.get("severity", "unknown")] += 1

    snap = json.loads(SNAPSHOT.read_text(encoding="utf-8"))
    at = datetime.fromisoformat(snap["written_at"])
    when = f"{at.day} {at:%b %Y}"
    same_ledger = snap["ledger_md5"] == hashlib.md5(ledger.DB.read_bytes()).hexdigest()

    rows = "\n".join(f"| {s} | {status[s]} |" for s in ledger.STATUSES if status[s])
    flags = ", ".join(f"{sev[s]} {s}" for s in ("high", "medium", "low"))
    flags += "".join(f", {n} {s}" for s, n in sev.items() if s not in ("high", "medium", "low"))
    return f"""{GEN_START}

| Claim status | Claims |
|---|---|
{rows}
| **Total** | **{sum(status.values())}** ({citable} citable in a brief) |

- **{quotes}** claims carry a source quote that `check_claims.py` re-finds in its source document.
- **{valid}/{total}** saved regional briefs pass `validate_brief.py` against the committed ledger.
- **{sum(sev.values())}** sentences flagged by the Hydrogen review for human reading ({flags}).
- Last full local verification, with all sources present: **{when}**, commit `{snap['commit'][:7]}`,
  `check_claims.py` {'passed' if snap['check_claims']['passed'] else 'FAILED'}
  ({'the committed ledger is the file verified then' if same_ledger else 'the ledger HAS CHANGED since'}).

{GEN_END}"""


def check(text: str, claims: dict[str, dict]) -> list[str]:
    problems, section, fenced, in_gen = [], "", False, False
    for no, line in enumerate(text.splitlines(), 1):
        for word in generic_county(MARKER.sub("", line)):           # every line, code and tables too
            problems.append(f"line {no}: generic {word!r}: say 'region(s)'; 'county' only for named counties")
        for n in re.findall(r"(\d+)\s+wellbeing services counties", line):
            if int(n) != N_WELLBEING_COUNTIES:
                problems.append(f"line {no}: {n} wellbeing services counties (the report has {N_WELLBEING_COUNTIES})")
        for n in re.findall(r"(\d+)\s+regions\b", line):
            if int(n) != N_REGIONS:
                problems.append(f"line {no}: {n} regions (the report has {N_REGIONS})")
        if line.startswith("```"):
            fenced = not fenced
            continue
        if line.startswith(GEN_START):
            in_gen = True
        if in_gen:
            in_gen = not line.startswith(GEN_END)
            continue
        if fenced:
            continue
        if line.startswith("#"):
            section = re.sub(r"^#+\s*(\d+\.\s*)?", "", line).strip()
            continue
        if section in SKIP_SECTIONS:
            continue

        ids = MARKER.search(line)
        body = MARKER.sub("", line)
        body = re.sub(r"`[^`]*`", "", body)                      # inline code: file names, model ids
        body = re.sub(r"\]\([^)]*\)", "]", body)                 # link targets
        body = re.sub(r"<[^>]+>", "", body)                      # html tags (logo, links)
        body = re.sub(r"\bq:[0-9a-f]{10}\b|\b[a-z]+:[\w:]+", "", body)  # claim ids in prose

        if not ids:
            for phrase in EXEMPT:
                body = body.replace(phrase, "")
            bad = [x for x, _ in numbers(body) if x not in FRAME]
            if bad:
                problems.append(f"line {no}: numbers {bad} with no <!-- claims: … --> marker")
            continue

        cited = []
        for cid in ids.group(1).split():
            c = claims.get(cid)
            if c is None:
                problems.append(f"line {no}: unknown claim {cid}")
            elif c["status"] not in ledger.CITABLE:
                problems.append(f"line {no}: claim {cid} is {c['status']!r}, not citable")
            else:
                cited.append(c)
        meta = " ".join(f"{c['location']} {c['notes'] or ''} {c['claim_text']}" for c in cited)

        for ref in LOC_TEXT.findall(body):
            if norm(ref) not in norm(meta):
                problems.append(f"line {no}: location {ref!r} not in the cited claims")
        want = pages(body)
        if want - pages(meta):
            problems.append(f"line {no}: page(s) {sorted(want - pages(meta))} not in the cited claims")
        body = PAGES.sub("", LOC_TEXT.sub("", body))

        pool = set().union(*(claim_numbers(c) for c in cited)) if cited else set()
        for x, d in numbers(body):
            if x not in FRAME and not matches(x, d, pool):
                problems.append(f"line {no}: {x:g} not in the cited claims")
    return problems


def main() -> int:
    claims = load_claims()
    text = README.read_text(encoding="utf-8")
    start, end = text.find(GEN_START), text.find(GEN_END)
    if start < 0 or end < 0:
        print("README.md has no generated block markers")
        return 1
    new = text[:start] + generated_block(claims) + text[end + len(GEN_END):]
    if "--check" in sys.argv:
        problems = [] if new == text else ["generated block is stale: run src/build_readme.py"]
    else:
        problems = []
        if new != text:
            README.write_text(new, encoding="utf-8", newline="\n")
            print("Updated the generated block in README.md")
    problems += check(new, claims)
    for p in problems:
        print("FAIL", p)
    print("README check passed" if not problems else f"{len(problems)} problem(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
